def _hash(strand, stop):
    return hashlib.sha256(f"{SALT}:{strand}:{stop}".encode()).hexdigest()[:16]


def _key(candidate):
    return (candidate["strand"], candidate["start"], candidate["stop"])


def _check_candidates(candidates):
    try:
        keys = [_key(c) for c in candidates]
    except (TypeError, KeyError):
        raise ValueError(
            "candidates must be a list of dictionaries, each with the keys "
            "'strand', 'start' and 'stop' (and 'protein')."
        ) from None
    text = ",".join(f"{s}:{a}:{b}" for s, a, b in sorted(keys))
    if hashlib.sha256(text.encode()).hexdigest() != CANDIDATE_SET_HASH:
        raise ValueError(
            f"These are not the expected candidates (you gave {len(keys)}, "
            f"there should be {N_CANDIDATES}). Make the find_candidates "
            "checkpoint pass before you score predictions."
        )
    return set(keys)


def score(predictions, candidates):
    """Count true and false positives and negatives for a list of predicted
    genes, which must be some of the candidates."""
    allowed = _check_candidates(candidates)
    predicted = set()
    for p in predictions:
        try:
            key = _key(p)
        except (TypeError, KeyError):
            raise ValueError(
                "Each prediction must be one of the candidate dictionaries."
            ) from None
        if key not in allowed:
            raise ValueError(f"This prediction is not one of the candidates: {p}")
        predicted.add(key)

    genes = {key for key in allowed if _hash(key[0], key[2]) in GENE_HASHES}
    counts = {
        "TP": len(predicted & genes),
        "FP": len(predicted - genes),
        "TN": len(allowed - predicted - genes),
        "FN": len(genes - predicted),
    }
    with open(LOG_FILE, "a", encoding="utf-8") as log:
        log.write(f"{datetime.now():%Y-%m-%d %H:%M:%S} "
                  f"predicted {len(predicted)}: {counts}\n")
    return counts
