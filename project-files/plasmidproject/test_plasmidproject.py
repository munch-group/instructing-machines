"""Checkpoint tests for the plasmid project.

These are not tests of your helper functions: you decide which helpers you
need and you write their tests yourself. These four tests check only the
fixed points of the project, the five functions whose names and formats
are given in the chapter:

    assemble_plasmid(file_name)          -> the plasmid as a string
    find_candidates(plasmid)             -> a list of candidate dictionaries
    sensitivity(counts), specificity(counts)  -> numbers between 0 and 1
    predict_genes(candidates, plasmid)   -> some of the candidates

Run them with:

    pytest test_plasmidproject.py
"""

import hashlib

import pytest
from pytest import approx
from im_pytest import requires

READS_FILE = "plasmid_reads.txt"

# BEGIN GENERATED by scripts/make_plasmidproject_data.py -- do not edit
PLASMID_LENGTH = 92721
PLASMID_SHA256 = "4934e58f3fe7f4293077936756edc45486701105e870939b5b0bfe5c3ca24fde"
N_CANDIDATES = 1922
N_PLUS = 962
N_MINUS = 960
CANDIDATE_SET_HASH = "b6dc3c181852b415dea8e679159ede7dc0a5aaf9959b4ab948bac8bcf8e46ba7"
# END GENERATED

CODON_MAP = {
    'TTT': 'F', 'TTC': 'F', 'TTA': 'L', 'TTG': 'L', 'TCT': 'S', 'TCC': 'S',
    'TCA': 'S', 'TCG': 'S', 'TAT': 'Y', 'TAC': 'Y', 'TAA': '*', 'TAG': '*',
    'TGT': 'C', 'TGC': 'C', 'TGA': '*', 'TGG': 'W', 'CTT': 'L', 'CTC': 'L',
    'CTA': 'L', 'CTG': 'L', 'CCT': 'P', 'CCC': 'P', 'CCA': 'P', 'CCG': 'P',
    'CAT': 'H', 'CAC': 'H', 'CAA': 'Q', 'CAG': 'Q', 'CGT': 'R', 'CGC': 'R',
    'CGA': 'R', 'CGG': 'R', 'ATT': 'I', 'ATC': 'I', 'ATA': 'I', 'ATG': 'M',
    'ACT': 'T', 'ACC': 'T', 'ACA': 'T', 'ACG': 'T', 'AAT': 'N', 'AAC': 'N',
    'AAA': 'K', 'AAG': 'K', 'AGT': 'S', 'AGC': 'S', 'AGA': 'R', 'AGG': 'R',
    'GTT': 'V', 'GTC': 'V', 'GTA': 'V', 'GTG': 'V', 'GCT': 'A', 'GCC': 'A',
    'GCA': 'A', 'GCG': 'A', 'GAT': 'D', 'GAC': 'D', 'GAA': 'E', 'GAG': 'E',
    'GGT': 'G', 'GGC': 'G', 'GGA': 'G', 'GGG': 'G',
}

# The plasmid and the candidates take a few seconds to compute, so each is
# computed once and shared by the tests that need it.
_cache = {}


def _sha256(text):
    return hashlib.sha256(text.encode()).hexdigest()


def _reverse_complement(seq):
    return seq[::-1].translate(str.maketrans("ACGT", "TGCA"))


def _translate(dna):
    return "".join(CODON_MAP[dna[i:i + 3]] for i in range(0, len(dna) - 2, 3))


def _plasmid(module):
    if "plasmid" not in _cache:
        _cache["plasmid"] = module.assemble_plasmid(READS_FILE)
    plasmid = _cache["plasmid"]
    if not (isinstance(plasmid, str) and _sha256(plasmid) == PLASMID_SHA256):
        pytest.skip("assemble_plasmid must pass before this checkpoint can be checked")
    return plasmid


def _candidates(module):
    plasmid = _plasmid(module)
    if "candidates" not in _cache:
        _cache["candidates"] = module.find_candidates(plasmid)
    return _cache["candidates"]


def _key(candidate):
    return (candidate["strand"], candidate["start"], candidate["stop"])


# --------------------------------------------------------------------------- #
# Checkpoint 1: the assembled plasmid
# --------------------------------------------------------------------------- #

@requires("assemble_plasmid")
def test_assemble_plasmid(module):
    _cache.pop("plasmid", None)
    plasmid = module.assemble_plasmid(READS_FILE)
    _cache["plasmid"] = plasmid
    assert isinstance(plasmid, str), \
        f"assemble_plasmid must return a string, not a {type(plasmid).__name__}"
    assert len(plasmid) == PLASMID_LENGTH, \
        f"The assembled plasmid is {len(plasmid)} bases long, but it should be {PLASMID_LENGTH}"
    assert _sha256(plasmid) == PLASMID_SHA256, \
        "The assembled plasmid has the right length but not the right sequence"


# --------------------------------------------------------------------------- #
# Checkpoint 2: the candidate ORFs
# --------------------------------------------------------------------------- #

@requires("assemble_plasmid", "find_candidates")
def test_find_candidates(module):
    plasmid = _plasmid(module)
    _cache.pop("candidates", None)
    candidates = _candidates(module)

    assert isinstance(candidates, list), \
        f"find_candidates must return a list, not a {type(candidates).__name__}"
    for c in candidates:
        assert isinstance(c, dict), f"Each candidate must be a dictionary, but found {c!r}"
        for k in ("strand", "start", "stop", "protein"):
            assert k in c, f"This candidate has no '{k}' key: {c}"
        assert c["strand"] in ("+", "-"), f"'strand' must be '+' or '-': {c}"

    plus = sum(c["strand"] == "+" for c in candidates)
    minus = len(candidates) - plus
    assert plus == N_PLUS and minus == N_MINUS, (
        f"You found {plus} candidates on the + strand and {minus} on the - strand. "
        f"There should be {N_PLUS} and {N_MINUS}."
    )

    stops = [(c["strand"], c["stop"]) for c in candidates]
    assert len(set(stops)) == len(stops), \
        "Two or more of your candidates share a stop codon. Keep only the longest one for each stop."

    text = ",".join(f"{s}:{a}:{b}" for s, a, b in sorted(_key(c) for c in candidates))
    assert _sha256(text) == CANDIDATE_SET_HASH, \
        "You have the right number of candidates, but not the right start and stop positions"

    strands = {"+": plasmid, "-": _reverse_complement(plasmid)}
    for c in candidates:
        expected = _translate(strands[c["strand"]][c["start"]:c["stop"]])
        assert c["protein"].rstrip("*") == expected, (
            f"The protein of this candidate is not the translation from its start "
            f"codon up to its stop codon: {c}"
        )


# --------------------------------------------------------------------------- #
# Checkpoint 3: sensitivity and specificity
# --------------------------------------------------------------------------- #

@requires("sensitivity", "specificity")
def test_sensitivity_and_specificity(module):
    counts = {"TP": 30, "FP": 10, "TN": 150, "FN": 10}
    assert module.sensitivity(counts) == approx(0.75)
    assert module.specificity(counts) == approx(150 / 160)

    everything = {"TP": 85, "FP": 1837, "TN": 0, "FN": 0}
    assert module.sensitivity(everything) == approx(1.0)
    assert module.specificity(everything) == approx(0.0)

    nothing = {"TP": 0, "FP": 0, "TN": 1837, "FN": 85}
    assert module.sensitivity(nothing) == approx(0.0)
    assert module.specificity(nothing) == approx(1.0)


# --------------------------------------------------------------------------- #
# Checkpoint 4: the predictions have the right form
# --------------------------------------------------------------------------- #

@requires("assemble_plasmid", "find_candidates", "predict_genes")
def test_predict_genes(module):
    plasmid = _plasmid(module)
    candidates = _candidates(module)
    predictions = module.predict_genes(candidates, plasmid)

    assert isinstance(predictions, list), \
        f"predict_genes must return a list, not a {type(predictions).__name__}"
    allowed = {_key(c) for c in candidates}
    keys = [_key(p) for p in predictions]
    for p, key in zip(predictions, keys):
        assert key in allowed, f"This prediction is not one of the candidates: {p}"
    assert len(set(keys)) == len(keys), "The same candidate is predicted more than once"
